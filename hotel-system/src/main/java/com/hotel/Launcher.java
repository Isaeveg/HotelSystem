package com.hotel;

/**
 * Entry point for the application to avoid JavaFX module issues.
 * <p>
 * This class simply calls {@link App#main(String[])}.
 * </p>
 */
public class Launcher {
    /**
     * Main entry point.
     *
     * @param args command line arguments
     */
    public static void main(String[] args) {
        App.main(args);
    }
}